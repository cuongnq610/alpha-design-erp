const server=http.createServer(async(req,res)=>{
  const requestIdValue=requestId(req);const baseHeaders=baseSecurityHeaders({requestIdValue});
  try{
    const url=new URL(req.url||'/','http://localhost');
    if(url.pathname.startsWith('/api/')){const handled=await handleApi(req,res,url,requestIdValue,baseHeaders);if(handled!==false)return;return send(res,404,{ok:false,error:'API không tồn tại.',requestId:requestIdValue},baseHeaders);}
    if(req.method==='GET'&&url.pathname==='/runtime-config.js'){res.writeHead(200,{...baseSecurityHeaders({requestIdValue}),'content-type':'text/javascript; charset=utf-8','cache-control':'no-store'});return res.end(runtimeConfigScript());}
    if(req.method!=='GET'&&req.method!=='HEAD')return send(res,405,{ok:false,error:'Phương thức không được hỗ trợ.',requestId:requestIdValue},baseHeaders);
    const file=safeFile(url.pathname==='/'?'/index.html':url.pathname);
    if(!file||!existsSync(file)||!statSync(file).isFile())return send(res,404,{ok:false,error:'Không tìm thấy tài nguyên.',requestId:requestIdValue},baseHeaders);
    const extension=extname(file).toLowerCase();const headers={...baseSecurityHeaders({requestIdValue,html:extension==='.html'}),'content-type':mime[extension]||'application/octet-stream','cache-control':extension==='.html'||extension==='.js'?'no-cache':'public, max-age=300'};
    res.writeHead(200,headers);if(req.method==='HEAD')return res.end();createReadStream(file).pipe(res);
  }catch(error){
    const status=Number(error.status)||500;
    const production=runtime.environment==='production';
    const publicMessage=production&&status>=500?(status===504?'Dịch vụ dữ liệu phản hồi quá thời gian.':'Dịch vụ tạm thời không khả dụng.'):error.message||'Lỗi máy chủ.';
    if(status>=500)console.error(`[${requestIdValue}]`,error);
    if(!res.headersSent)send(res,status,{ok:false,error:publicMessage,code:error.code||'SERVER_ERROR',requestId:requestIdValue},baseHeaders);else res.end();
  }
});
server.requestTimeout=Math.trunc(finiteNumber(process.env.REQUEST_TIMEOUT_MS,30000,5000,120000));
server.headersTimeout=Math.min(server.requestTimeout,Math.trunc(finiteNumber(process.env.HEADERS_TIMEOUT_MS,15000,5000,60000)));
server.keepAliveTimeout=Math.trunc(finiteNumber(process.env.KEEP_ALIVE_TIMEOUT_MS,5000,1000,30000));
server.maxHeadersCount=100;
server.listen(port,host,()=>console.log(`ALPHA DESIGN ERP v${VERSION.version}: http://${host}:${port} (${runtime.authoritative?'server-authoritative':'demo-compatible'})`));
